/* dmr - drax manager & resolver */

#define _GNU_SOURCE
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#include "dlock.h"
#include "dfs.h"

lock_pkg* lock_add(lock_file* l, const char* name) {
  if (l->n >= l->cap) {
    l->cap = l->cap == 0 ? 8 : l->cap * 2;
    l->pkgs = (lock_pkg*) xrealloc(l->pkgs, sizeof(lock_pkg) * (size_t) l->cap);
  }
  lock_pkg* p = &l->pkgs[l->n++];
  memset(p, 0, sizeof(*p));
  p->name = xstrdup(name);
  return p;
}

lock_pkg* lock_find(lock_file* l, const char* name) {
  int i;
  for (i = 0; i < l->n; i++) {
    if (strcmp(l->pkgs[i].name, name) == 0) return &l->pkgs[i];
  }
  return NULL;
}

void lock_pkg_dep(lock_pkg* p, const char* dep) {
  p->deps = (char**) xrealloc(p->deps, sizeof(char*) * (size_t) (p->ndeps + 1));
  p->deps[p->ndeps++] = xstrdup(dep);
}

void lock_free(lock_file* l) {
  int i, j;
  for (i = 0; i < l->n; i++) {
    lock_pkg* p = &l->pkgs[i];
    free(p->name); free(p->source); free(p->requested); free(p->rev);
    for (j = 0; j < p->ndeps; j++) free(p->deps[j]);
    free(p->deps);
  }
  free(l->pkgs);
  memset(l, 0, sizeof(*l));
}

static int cmp_pkg(const void* a, const void* b) {
  return strcmp(((const lock_pkg*) a)->name, ((const lock_pkg*) b)->name);
}

static int cmp_strp(const void* a, const void* b) {
  return strcmp(*(char* const*) a, *(char* const*) b);
}

static void put_quoted(FILE* f, const char* s) {
  fputc('"', f);
  for (; *s; s++) {
    if (*s == '"' || *s == '\\') fputc('\\', f);
    fputc(*s, f);
  }
  fputc('"', f);
}

int lock_save(const char* path, lock_file* l) {
  int i, j;
  FILE* f = fopen(path, "wb");
  if (!f) return 1;

  qsort(l->pkgs, (size_t) l->n, sizeof(lock_pkg), cmp_pkg);

  fprintf(f, "# This file is generated by dmr. Do not edit it.\n");
  fprintf(f, "version = 1\n");

  for (i = 0; i < l->n; i++) {
    lock_pkg* p = &l->pkgs[i];
    fprintf(f, "\n[[package]]\nname = ");
    put_quoted(f, p->name);
    fprintf(f, "\nsource = ");
    put_quoted(f, p->source ? p->source : "");
    fprintf(f, "\n");
    if (p->requested) { fprintf(f, "requested = "); put_quoted(f, p->requested); fprintf(f, "\n"); }
    if (p->rev) { fprintf(f, "rev = "); put_quoted(f, p->rev); fprintf(f, "\n"); }
    if (p->ndeps > 0) {
      qsort(p->deps, (size_t) p->ndeps, sizeof(char*), cmp_strp);
      fprintf(f, "dependencies = [");
      for (j = 0; j < p->ndeps; j++) {
        if (j) fprintf(f, ", ");
        put_quoted(f, p->deps[j]);
      }
      fprintf(f, "]\n");
    }
  }
  return fclose(f) == 0 ? 0 : 1;
}

/* reads a "..." string, unescaping \" and \\ */
static char* read_quoted(const char** pp) {
  const char* p = *pp;
  if (*p != '"') return NULL;
  p++;
  size_t cap = 32, n = 0;
  char* b = (char*) xrealloc(NULL, cap);
  while (*p && *p != '"') {
    if (*p == '\\' && p[1]) p++;
    if (n + 2 >= cap) { cap *= 2; b = (char*) xrealloc(b, cap); }
    b[n++] = *p++;
  }
  if (*p != '"') { free(b); return NULL; }
  b[n] = 0;
  *pp = p + 1;
  return b;
}

int lock_load(const char* path, lock_file* l, char* err, int errsz) {
  memset(l, 0, sizeof(*l));

  char* text = fs_read(path, NULL);
  if (text == NULL) return 0; /* no lock yet */

  lock_pkg* cur = NULL;
  int line = 0, rc = 0;
  char* p = text;

  while (*p && rc == 0) {
    char* eol = strchr(p, '\n');
    if (eol) *eol = 0;
    line++;
    char* s = p;
    p = eol ? eol + 1 : p + strlen(p);

    while (*s == ' ' || *s == '\t' || *s == '\r') s++;
    if (*s == 0 || *s == '#') continue;

    if (strncmp(s, "[[package]]", 11) == 0) {
      cur = lock_add(l, "");
      free(cur->name);
      cur->name = NULL;
      continue;
    }

    char* eq = strchr(s, '=');
    if (!eq) { snprintf(err, (size_t) errsz, "line %d: invalid line.", line); rc = 1; break; }
    char* kend = eq;
    while (kend > s && (kend[-1] == ' ' || kend[-1] == '\t')) kend--;
    *kend = 0;
    const char* v = eq + 1;
    while (*v == ' ' || *v == '\t') v++;

    if (cur == NULL) continue; /* header: version = 1 */

    if (strcmp(s, "dependencies") == 0) {
      if (*v != '[') { snprintf(err, (size_t) errsz, "line %d: invalid list.", line); rc = 1; break; }
      v++;
      for (;;) {
        while (*v == ' ' || *v == ',') v++;
        if (*v == ']') break;
        char* d = read_quoted(&v);
        if (!d) { snprintf(err, (size_t) errsz, "line %d: invalid list.", line); rc = 1; break; }
        lock_pkg_dep(cur, d);
        free(d);
      }
      continue;
    }

    char* val = read_quoted(&v);
    if (!val) { snprintf(err, (size_t) errsz, "line %d: invalid value.", line); rc = 1; break; }

    if (strcmp(s, "name") == 0) { free(cur->name); cur->name = val; }
    else if (strcmp(s, "source") == 0) { free(cur->source); cur->source = val; }
    else if (strcmp(s, "requested") == 0) { free(cur->requested); cur->requested = val; }
    else if (strcmp(s, "rev") == 0) { free(cur->rev); cur->rev = val; }
    else free(val);
  }

  free(text);

  int i;
  for (i = 0; rc == 0 && i < l->n; i++) {
    if (l->pkgs[i].name == NULL || l->pkgs[i].source == NULL) {
      snprintf(err, (size_t) errsz, "a package without name or source.");
      rc = 1;
    }
  }
  if (rc) lock_free(l);
  return rc;
}
