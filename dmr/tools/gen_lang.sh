#!/bin/sh
# dmr - drax manager & resolver
#
# Generates src/dlang_data.c (the keywords, global functions and native
# modules of the Drax language) from the sources of the interpreter.
#
#   sh tools/gen_lang.sh ../src > src/dlang_data.c
#
# dmr does not link the interpreter: this table is the only coupling with
# it, and `make lang-check` fails when the committed table is stale.
set -e
SRC=${1:-../src}

echo "/* generated by tools/gen_lang.sh from the Drax sources: do not edit */"
echo '#include "dlang.h"'
echo

echo "const char* const DLANG_KEYWORDS[] = {"
sed -n 's/^ *{"\([a-z_]*\)", *DTK_[A-Z_]*}.*/\1/p' "$SRC/dlex.c" | LC_ALL=C sort -u | awk '{ printf "  \"%s\",\n", $0 }'
echo "  0"
echo "};"
echo

echo "const char* const DLANG_BUILTINS[] = {"
sed -n 's/^ *reg(vm, "\([a-z_]*\)", *\([0-9]*\),.*/\1\/\2/p' "$SRC/dbuiltin.c" | LC_ALL=C sort -u | awk '{ printf "  \"%s\",\n", $0 }'
echo "  0"
echo "};"
echo

# Module<TAB>name/arity, from the helper tables of create_native_modules
PAIRS=$(awk '
  /new_native_module\(vm, "/ {
    match($0, /"[A-Za-z_]+"/); mod = substr($0, RSTART + 1, RLENGTH - 2); next
  }
  mod != "" && /^ *\{[0-9]+, *"[a-z_0-9]+"/ {
    match($0, /\{[0-9]+/); ar = substr($0, RSTART + 1, RLENGTH - 1)
    match($0, /"[a-z_0-9]+"/); nm = substr($0, RSTART + 1, RLENGTH - 2)
    print mod "\t" nm "/" ar; next
  }
  /^ *};/ { mod = "" }
' "$SRC/dbuiltin.c" | LC_ALL=C sort -u)

echo "$PAIRS" | awk -F'\t' '
  { if ($1 != cur) { if (cur != "") print "  0\n};\n"; cur = $1; print "static const char* const MOD_" cur "[] = {" }
    printf "  \"%s\",\n", $2 }
  END { print "  0\n};\n" }'

echo "const dlang_module DLANG_MODULES[] = {"
echo "$PAIRS" | cut -f1 | LC_ALL=C sort -u | awk '{ printf "  { \"%s\", MOD_%s },\n", $0, $0 }'
echo "  { 0, 0 }"
echo "};"
